texts = []
services = []

for category, examples in sample_texts.items():
    for text in examples:
        texts.append(text)
        services.append(category)

df = pd.DataFrame({
    "text": texts,
    "service": services
})

model_pipeline = Pipeline([
    ('tfidf', TfidfVectorizer(
        ngram_range=(1, 3),
        analyzer='char_wb'
    )),
    ('clf', LinearSVC(
        C=1.0,
        random_state=42
    ))
])


model_pipeline.fit(df['text'], df['service'])
joblib.dump(
    model_pipeline,
    "app/model/model.pkl"
)

